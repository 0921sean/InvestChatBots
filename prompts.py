def format_history(messages):
    return "\n".join(f"{m['agent_name']}: {m['content']}" for m in messages)


def format_history_compact(messages):
    lines = []
    for m in messages:
        text = m.get("summary") or m["content"][:120].replace("\n", " ")
        lines.append(f"{m['agent_name']}: {text}")
    return "\n".join(lines)


